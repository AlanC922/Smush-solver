"""Build words.js, the website's dictionary, from ../dictionary.txt.

Keeps words of 3+ letters with at most 9 distinct letters (no board can play
anything else), in file order, so the site's word lists match
smush_engine.Dictionary.playable exactly.

  python web/build_words.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "dictionary.txt")
OUT = os.path.join(HERE, "words.js")


def main():
    with open(SRC, "r", encoding="utf-8") as f:
        words = [w for w in (line.strip().lower() for line in f) if len(w) >= 3 and len(set(w)) <= 9]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by build_words.py from dictionary.txt. Do not edit by hand.\n")
        f.write(f"globalThis.SMUSH_WORDS = {json.dumps(chr(10).join(words))};\n")
    print(f"wrote {OUT}: {len(words)} words, {os.path.getsize(OUT) / 1e6:.2f} MB")


if __name__ == "__main__":
    main()
